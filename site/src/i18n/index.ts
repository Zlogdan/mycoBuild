const dicts: Record<Lang, Record<TKey, string>> = { ru, en };

export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? ru[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Localised game string with fallback to English, then to any language. */
export function loc(l: Loc | null | undefined, lang: Lang): string {
  if (!l) return '';
  return l[lang] ?? l.en ?? Object.values(l)[0] ?? '';
}
